// Inline every assets/**/*.svg into src/components/svgIcons.js so icons are drawn with
// <SvgXml xml={...}>. Release APKs rename bundled resources (res/-B.svg ...), and
// <SvgUri uri={asset.localUri}> then silently draws nothing on Android.
// Run after adding or editing an SVG:  node scripts/generate-svg-icons.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(root, "assets");
export const OUTPUT = join(root, "src", "components", "svgIcons.js");

function svgFiles(dir) {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) return svgFiles(path);
      return name.endsWith(".svg") ? [path] : [];
    });
}

export function render() {
  const entries = svgFiles(assets).map((file) => {
    const key = relative(assets, file).replaceAll("\\", "/").replace(/\.svg$/, "");
    const xml = readFileSync(file, "utf8").replace(/<\?xml[^>]*>\s*/, "").trim();
    return `  ${JSON.stringify(key)}: ${JSON.stringify(xml)},`;
  });
  return (
    "// Generated by scripts/generate-svg-icons.mjs from assets/**/*.svg. Do not edit by hand.\n" +
    "export const svgIcons = {\n" +
    entries.join("\n") +
    "\n};\n"
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, render());
  console.log(`wrote ${relative(root, OUTPUT)}`);
}
