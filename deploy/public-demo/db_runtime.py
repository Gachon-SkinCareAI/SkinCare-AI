"""Linux adapter reusing the existing migration/erasure/retention implementation."""
from contextlib import contextmanager
import json
import os
from pathlib import Path
import re
import sys

sys.path.insert(0, '/opt/mysql-tools')
from manage import Instance, identifier

def root_password(path):
    # The MySQL image uses shell command substitution for *_FILE: it removes
    # trailing LF bytes, but preserves CR. Match it for existing Windows QA
    # bundles without changing the database password or discarding its volume.
    value = Path(path).read_bytes().decode('ascii').rstrip('\n')
    if not re.fullmatch(r'[0-9a-f]{64}\r?', value):
        raise RuntimeError('Database credentials must be generated by prepare_bundle.py')
    return value

def option_password(value):
    # MySQL option files recognize the escaped carriage return. A literal CR
    # would instead be interpreted as a line ending.
    return value.replace('\r', '\\r')

class ContainerInstance(Instance):
    def __init__(self):
        self.root = Path('/state')
        self.root.mkdir(exist_ok=True)
        self.private = self.root / 'private'
        self.private.mkdir(mode=0o700, exist_ok=True)
        self.private.chmod(0o700)
        self.data = Path('/var/lib/mysql')
        self.port = 3306
        self.bin = Path('/usr/bin')
        for role, filename, username in [('root','db_root','root'), ('app','db_app','skincare_app')]:
            password = (root_password('/run/secrets/' + filename) if role == 'root'
                        else Path('/run/secrets/' + filename).read_text().strip())
            if not re.fullmatch(r'[0-9a-f]{64}\r?' if role == 'root' else r'[0-9a-f]{64}', password):
                raise RuntimeError('Database credentials must be generated by prepare_bundle.py')
            path = self.private / (role + '.cnf')
            path.write_text('[client]\nuser=' + username + '\npassword=' + option_password(password) + '\n', encoding='utf-8')
            path.chmod(0o600)

    def client(self, exe='mysql.exe', account='root'):
        if account not in ('root', 'app') or exe not in ('mysql.exe', 'mysqldump.exe'):
            raise ValueError('Unsupported database client')
        return [self.bin / exe.removesuffix('.exe'), '--defaults-file=' + str(self.private/(account+'.cnf')),
                '--protocol=TCP', '--host=db', '--port=3306', '--ssl-mode=REQUIRED']

    def check_identity(self):
        row = self.sql('SELECT @@server_uuid,@@datadir;').split('\t')
        if len(row) != 2 or Path(row[1]) != self.data:
            raise RuntimeError('Unexpected database identity')
        marker = self.root/'server-identity.json'
        if marker.exists():
            if json.loads(marker.read_text()) != {'serverUuid': row[0], 'database': 'skincare_dev'}:
                raise RuntimeError('Database volume identity changed; manual recovery required')
        else:
            if self.sql("SELECT COUNT(*) FROM information_schema.schemata WHERE schema_name='skincare_dev';") != '0':
                raise RuntimeError('Refusing to adopt an existing unmarked database')
            # First initialization only; fail closed if the state volume later goes missing.
            with marker.open('x') as stream:
                json.dump({'serverUuid': row[0], 'database': 'skincare_dev'}, stream)
            marker.chmod(0o600)

    @contextmanager
    def lock(self):
        import fcntl
        with (self.root/'maintenance.lock').open('a+b') as stream:
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                raise RuntimeError('Another maintenance operation is running')
            try:
                yield
            finally:
                fcntl.flock(stream, fcntl.LOCK_UN)

    def grant_app(self, name):
        password = Path('/run/secrets/db_app').read_text().strip()
        if not re.fullmatch('[0-9a-f]{64}', password):
            raise RuntimeError('Invalid generated credential')
        self.sql("CREATE USER IF NOT EXISTS 'skincare_app'@'%' IDENTIFIED BY '"+password+"';")
        # This account is created here, not with MYSQL_USER (which grants schema ownership).
        self.sql('GRANT SELECT, INSERT, UPDATE, DELETE ON '+identifier(name)+".* TO 'skincare_app'@'%';")

    def start(self):
        raise RuntimeError('Docker Compose owns the database lifecycle')

    def stop(self):
        raise RuntimeError('Docker Compose owns the database lifecycle')
